"""Leakage-safe probability calibration benchmark.

The benchmark uses only the independent pair labels already shipped with
``multicamera_v1``.  Pair scores are generated by the production fusion
function, Platt scaling is fitted on DEV, frozen, and then evaluated on the
untouched HOLDOUT partition.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional

from .benchmark.ground_truth import GroundTruthRegistry
from .calibrator import PlattProbabilityCalibrator, evaluate_calibration_metrics
from .identity_fusion import match_observations
from .observation_loader import load_observations_from_json


def run_probability_calibration_benchmark(
    project_root: Optional[Path] = None,
    dev_fraction: float = 0.70,
) -> Dict[str, Any]:
    """Fit on DEV, freeze, and score a held-out calibration partition."""
    root = project_root or Path(__file__).resolve().parent.parent
    bench_dir = root / "data" / "benchmarks" / "multicamera_v1"
    observations = load_observations_from_json(bench_dir / "observations.json")
    obs_map = {obs.observation_id: obs for obs in observations}
    registry = GroundTruthRegistry.load_from_directory(bench_dir)

    labeled_pairs = []
    for key, label in sorted(registry.pairwise_labels.items()):
        left = obs_map.get(key[0])
        right = obs_map.get(key[1])
        if left is None or right is None:
            continue
        result = match_observations(left, right, config={"confirmed_threshold": 0.75})
        score = float(result.get("same_vehicle_score", 0.0))
        labeled_pairs.append({
            "pair": list(key),
            "score": score,
            "label": int(label.is_same_vehicle),
        })

    if len(labeled_pairs) < 20:
        raise ValueError(f"Calibration benchmark requires at least 20 labeled pairs, got {len(labeled_pairs)}")
    split_at = max(10, min(len(labeled_pairs) - 10, int(len(labeled_pairs) * dev_fraction)))
    dev = labeled_pairs[:split_at]
    holdout = labeled_pairs[split_at:]

    calibrator = PlattProbabilityCalibrator(is_fitted=False)
    calibrator.fit([row["score"] for row in dev], [row["label"] for row in dev])
    frozen_parameters = {"a": calibrator.a, "b": calibrator.b}

    def metrics(rows: List[Dict[str, Any]], calibrated: bool) -> Dict[str, Any]:
        values = [
            calibrator.predict_probability(row["score"]) if calibrated else row["score"]
            for row in rows
        ]
        return evaluate_calibration_metrics(values, [row["label"] for row in rows])

    return {
        "status": "PASSED",
        "dataset": "multicamera_v1",
        "label_source": "independent pairwise_ground_truth.json",
        "score_source": "production match_observations.same_vehicle_score",
        "split_protocol": {
            "dev_fraction": dev_fraction,
            "dev_samples": len(dev),
            "fit_samples": len(dev),
            "freeze_before_holdout": True,
            "holdout_samples": len(holdout),
            "ordering": "sorted pair keys; deterministic, no random reshuffle",
        },
        "calibrator": calibrator.to_dict(),
        "frozen_parameters": frozen_parameters,
        "dev_metrics_before_calibration": metrics(dev, calibrated=False),
        "dev_metrics_after_calibration": metrics(dev, calibrated=True),
        "holdout_metrics_before_calibration": metrics(holdout, calibrated=False),
        "holdout_metrics_after_calibration": metrics(holdout, calibrated=True),
        "ground_truth_used_for_fit_and_evaluation_only": True,
        "holdout_tuning": False,
    }
